"""One-off script (Phase 2): introspect the ACTUALLY INSTALLED tsl package for
the real GraphWaveNet / AGCRN class names and constructor signatures, rather
than guessing from memory or from possibly-stale online examples. Prints
findings and appends them to code/API_NOTES.md.

Run: .venv/Scripts/python.exe -m code.experiments.introspect_api
"""
from __future__ import annotations

import inspect
from pathlib import Path

_ROOT = Path(__file__).resolve().parents[2]


def _find_candidates(module, keywords):
    found = {}
    for name in dir(module):
        if name.startswith("_"):
            continue
        low = name.lower()
        if any(k in low for k in keywords):
            found[name] = getattr(module, name)
    return found


def main():
    import tsl
    import tsl.nn.models as models_mod

    all_names = [n for n in dir(models_mod) if not n.startswith("_")]

    gwn_candidates = _find_candidates(models_mod, ["wavenet", "gwn"])
    agcrn_candidates = _find_candidates(models_mod, ["agcrn"])

    lines = [f"# API Notes (tsl {tsl.__version__})", "",
             "Generated by `code/experiments/introspect_api.py` against the ACTUALLY "
             "INSTALLED tsl version -- authoritative for this project, supersedes any "
             "assumption made before installation.", "",
             "## Full `tsl.nn.models` member list", ""]
    for n in all_names:
        lines.append(f"- `{n}`")
    lines.append("")

    for label, candidates in [("GraphWaveNet", gwn_candidates), ("AGCRN", agcrn_candidates)]:
        lines.append(f"## {label} candidates")
        lines.append("")
        if not candidates:
            lines.append(f"**No class matching '{label.lower()}' found in tsl.nn.models.** "
                          f"Will need to search other submodules (tsl.nn.models.*, tsl.nn.blocks).")
        for name, obj in candidates.items():
            lines.append(f"### `{name}`")
            if inspect.isclass(obj):
                try:
                    sig = inspect.signature(obj.__init__)
                    lines.append(f"```python\n{name}{sig}\n```")
                except (ValueError, TypeError) as e:
                    lines.append(f"(could not get signature: {e})")
                doc = inspect.getdoc(obj)
                if doc:
                    lines.append(f"\n{doc}\n")
            lines.append("")

    text = "\n".join(lines)
    print(text)

    out_path = _ROOT / "code" / "API_NOTES.md"
    out_path.write_text(text, encoding="utf-8")
    print(f"\n\nWritten to {out_path}")


if __name__ == "__main__":
    main()
